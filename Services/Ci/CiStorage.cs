using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.Extensions.Options;

namespace GitBench.Services.Ci;

/// <summary>A job's <c>artifacts</c> and <c>cache</c> settings, stored as JSON on <see cref="Data.PipelineJob.ExtrasJson"/>.</summary>
public sealed record CiJobExtras(CiArtifactsDefinition? Artifacts, CiCacheDefinition? Cache, CiPagesDefinition? Pages = null)
{
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

    public static string? Serialize(CiJobDefinition j) =>
        j.Artifacts == null && j.Cache == null && j.Pages == null ? null : JsonSerializer.Serialize(new CiJobExtras(j.Artifacts, j.Cache, j.Pages), Json);

    public static CiJobExtras Parse(string? json)
    {
        if (string.IsNullOrEmpty(json)) return new(null, null);
        try { return JsonSerializer.Deserialize<CiJobExtras>(json, Json) ?? new(null, null); }
        catch (JsonException) { return new(null, null); }
    }

    /// <summary>A pipeline's extra variables (<see cref="Data.Pipeline.VariablesJson"/>).</summary>
    public static Dictionary<string, string> ParseVariables(string? json)
    {
        if (string.IsNullOrEmpty(json)) return [];
        try { return JsonSerializer.Deserialize<Dictionary<string, string>>(json) ?? []; }
        catch (JsonException) { return []; }
    }

    public static string? SerializeVariables(IReadOnlyDictionary<string, string>? vars) =>
        vars == null || vars.Count == 0 ? null : JsonSerializer.Serialize(vars);
}

/// <summary>
/// Folders for artifacts (<c>Ci:ArtifactsRoot</c>) and caches (<c>Ci:CacheRoot</c>), both under the content root by
/// default. Stored names are generated by GitBench (<c>{repoId}/{guid}.zip</c>) and checked before use.
/// </summary>
public sealed partial class CiStorage(IOptionsMonitor<CiOptions> options, IWebHostEnvironment env)
{
    [GeneratedRegex("^[0-9]{1,10}/[0-9a-f]{32}\\.zip$")]
    private static partial Regex StoredNamePattern();

    public string ArtifactsRoot => Path.GetFullPath(options.CurrentValue.ArtifactsRoot is { Length: > 0 } a ? a : Path.Combine(env.ContentRootPath, "ci-artifacts"));
    public string CacheRoot => Path.GetFullPath(options.CurrentValue.CacheRoot is { Length: > 0 } c ? c : Path.Combine(env.ContentRootPath, "ci-cache"));

    public static string NewStoredName(int repositoryId) => $"{repositoryId}/{Guid.NewGuid():N}.zip";

    public string ArtifactPath(string storedName) => Resolve(ArtifactsRoot, storedName);
    public string CachePath(string storedName) => Resolve(CacheRoot, storedName);

    private static string Resolve(string root, string storedName)
    {
        if (!StoredNamePattern().IsMatch(storedName)) throw new InvalidOperationException("Invalid stored file name.");
        return Path.Combine(root, storedName.Replace('/', Path.DirectorySeparatorChar));
    }
}
